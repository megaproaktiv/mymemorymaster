const dicts: Record<Lang, Dict> = { en, de };

let current: Lang = "en";

export async function initI18n(): Promise<Lang> {
  try {
    const stored = (await GetLanguage()) as Lang;
    if (stored === "en" || stored === "de") current = stored;
  } catch {
    current = "en";
  }
  return current;
}

export function lang(): Lang {
  return current;
}

export async function setLang(l: Lang): Promise<void> {
  current = l;
  try {
    await SetLanguage(l);
  } catch {
    /* ignore persistence errors */
  }
}

export function t(key: string): string {
  return dicts[current][key] ?? dicts.en[key] ?? key;
}
